#!/usr/bin/env python3
"""Aggregate benchmarks/**/*.json into docs/BENCHMARKS.md.

  aggregate.py            # write docs/BENCHMARKS.md
  aggregate.py --check    # fail if it is stale
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "BENCHMARKS.md"


def load_reports(root: Path = ROOT / "benchmarks") -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(root.glob("*/*.json"))]


def _median(values: list[float]) -> str:
    return f"{statistics.median(values):.1f}" if values else "—"


def _gib(n: float | None) -> str:
    return f"{n / 1024**3:.2f}" if n else "—"


def render(reports: list[dict], catalog: dict) -> str:
    names = {m["id"]: m.get("name", m["id"]) for m in catalog["models"]}
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in reports:
        groups[(r["model"]["id"], r["device"]["model"])].append(r)

    lines = [
        "# GUS on-device benchmarks",
        "",
        "Generated by `scripts/benchmarks/aggregate.py` from `benchmarks/`. Do not edit by hand.",
        "",
        "Results come from the in-app benchmark (protocol v1: greedy decoding, 2K context, 4 fixed tasks),",
        "submitted through the *GUS benchmark result* issue form and approved by a maintainer.",
        "Devices are listed by hardware id (`iPhone13,2` = iPhone 12). **KILLED** means iOS terminated the app:",
        "the model did not fit in that device's memory limit at that moment.",
        "",
    ]
    if not reports:
        lines += ["No results yet. Run *Modelos locales → Benchmark en este iPhone* and publish the JSON.", ""]
        return "\n".join(lines)

    lines += [
        "| Model | Device | Runs | Completed | Killed | Gen tok/s (median) | Prefill tok/s (median) | Load s (median) | Peak GiB (max) | Checks passed |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for (model_id, device), runs in sorted(groups.items()):
        completed = [r for r in runs if r["status"] == "completed"]
        killed = sum(1 for r in runs if r["status"] == "killed")
        gen = [t["gen_tok_s"] for r in completed for t in r["tasks"] if t["id"] == "sustained-generation"]
        prefill = [t["prefill_tok_s"] for r in completed for t in r["tasks"] if t["id"] == "long-prefill"]
        load = [r["load_ms"] / 1000 for r in completed if r.get("load_ms")]
        peak = max((r["peak_footprint_bytes"] for r in runs), default=None)
        checks = [t["passed"] for r in completed for t in r["tasks"]]
        passed = f"{sum(checks)}/{len(checks)}" if checks else "—"
        lines.append(f"| {names.get(model_id, model_id)} | {device} | {len(runs)} | {len(completed)} | {killed} | "
                     f"{_median(gen)} | {_median(prefill)} | {_median(load)} | {_gib(peak)} | {passed} |")
    lines += ["", f"{len(reports)} result(s) from {len({r['device']['model'] for r in reports})} device model(s).", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    catalog = json.loads((ROOT / "Catalog" / "models.json").read_text(encoding="utf-8"))
    text = render(load_reports(), catalog)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print("docs/BENCHMARKS.md is stale; run scripts/benchmarks/aggregate.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
